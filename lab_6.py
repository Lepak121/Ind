import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.datasets import fetch_openml
from sklearn.preprocessing import StandardScaler
from minisom import MiniSom

# ==========================================
# 1. ЗАВАНТАЖЕННЯ ТА ПІДГОТОВКА ДАНИХ
# ==========================================
boston = fetch_openml(name='boston', version=1, as_frame=True, parser='auto')
df = boston.frame

features = ['INDUS', 'DIS', 'NOX', 'LSTAT', 'AGE', 'RAD', 'B']
X = df[features].dropna()

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

print(f"Розмір вибірки: {X_scaled.shape[0]} спостережень, {X_scaled.shape[1]} факторів\n")

# ==========================================
# 2. ІНІЦІАЛІЗАЦІЯ ТА НАВЧАННЯ МЕРЕЖІ SOM
# ==========================================
grid_rows, grid_cols = 9, 6
input_len = X_scaled.shape[1]

som = MiniSom(
    x=grid_rows,
    y=grid_cols,
    input_len=input_len,
    sigma=1.0,
    learning_rate=0.5,
    random_seed=42
)

som.random_weights_init(X_scaled)

num_iterations = 100
quantization_errors = []

print("Початок навчання SOM...")
for i in range(num_iterations):
    som.train_random(X_scaled, 1, verbose=False)
    q_err = som.quantization_error(X_scaled)
    quantization_errors.append(q_err)

print(f"Початкова похибка квантування: {quantization_errors[0]:.4f}")
print(f"Кінцева похибка квантування:   {quantization_errors[-1]:.4f}\n")

# ==========================================
# 3. ВІЗУАЛІЗАЦІЯ РЕЗУЛЬТАТІВ (Графіки)
# ==========================================

# А. Графік динаміки похибки квантування
plt.figure(figsize=(9, 4), dpi=100)
plt.plot(range(1, num_iterations + 1), quantization_errors, marker='o', markersize=3, color='#1f77b4')
plt.title('Динаміка похибки квантування (Quantization Error)', fontsize=11)
plt.xlabel('Ітерація навчання', fontsize=9)
plt.ylabel('Quantization Error', fontsize=9)
plt.grid(True, linestyle=':', alpha=0.6)
plt.tight_layout()
plt.show()

# Б. U-Matrix та матриця активацій
fig, axes = plt.subplots(1, 2, figsize=(12, 5), dpi=100)

u_matrix = som.distance_map()
im0 = axes[0].imshow(u_matrix.T, cmap='bone_r', interpolation='nearest')
axes[0].set_title('U-Matrix (Карта відстаней)', fontsize=11)
fig.colorbar(im0, ax=axes[0], fraction=0.046, pad=0.04)

activation_freq = som.activation_response(X_scaled)
im1 = axes[1].imshow(activation_freq.T, cmap='Blues', interpolation='nearest')
axes[1].set_title('Матриця активацій (Activation Frequency)', fontsize=11)
fig.colorbar(im1, ax=axes[1], fraction=0.046, pad=0.04)

for ax in axes:
    ax.set_xticks(range(grid_cols))
    ax.set_yticks(range(grid_rows))
    ax.grid(True, linestyle='--', alpha=0.3, color='gray')
    ax.set_xlabel('Колонка сітки', fontsize=9)
    ax.set_ylabel('Рядок сітки', fontsize=9)

plt.tight_layout()
plt.show()

# В. Компонентні площини (Component Planes)
fig, axes = plt.subplots(2, 4, figsize=(16, 8), dpi=100)
axes = axes.flatten()

weights = som.get_weights()

for idx, feat_name in enumerate(features):
    ax = axes[idx]
    component_grid = weights[:, :, idx]
    im = ax.imshow(component_grid.T, cmap='coolwarm', interpolation='nearest')
    ax.set_title(f'Компонента: {feat_name}', fontsize=10)
    fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    ax.set_xticks(range(grid_cols))
    ax.set_yticks(range(grid_rows))
    ax.grid(True, linestyle='--', alpha=0.3, color='gray')

axes[7].axis('off')
plt.suptitle('Компонентні площини (Component Planes) ознак Boston Housing у просторі SOM', fontsize=13, y=1.02)
plt.tight_layout()
plt.show()

# Г. Проєкція спостережень на карту (BMU Scatter Plot за LSTAT)
target_feature_idx = features.index('LSTAT')
target_values = X[features[target_feature_idx]].values

plt.figure(figsize=(10, 7), dpi=100)
plt.imshow(u_matrix.T, cmap='bone_r', alpha=0.6, interpolation='nearest')
plt.colorbar(label='U-Matrix (структура відстаней)')

np.random.seed(42)
for i, x_val in enumerate(X_scaled):
    w = som.winner(x_val)
    wx = w[1] + np.random.uniform(-0.3, 0.3)
    wy = w[0] + np.random.uniform(-0.3, 0.3)
    plt.scatter(wx, wy, c=[target_values[i]], cmap='viridis', edgecolors='black', s=35, linewidths=0.5)

plt.colorbar(label=f'{features[target_feature_idx]} (% населення з низьким соц.-екон. статусом)')
plt.title(f'Проєкція спостережень на карту Кохонена (BMU) з розфарбуванням за {features[target_feature_idx]}', fontsize=11)
plt.xlabel('Нейрон X (0-8)', fontsize=9)
plt.ylabel('Нейрон Y (0-5)', fontsize=9)
plt.grid(True, linestyle='--', alpha=0.3)
plt.tight_layout()
plt.show()